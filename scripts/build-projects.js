import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateNote } from "../src/note-format.js";
import { publicationHTML } from "../tools/editor/publication.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function loadCollection(folder, kind) {
  const source = resolve(root, "content", folder);
  const files = (await readdir(source)).filter((file) => file.endsWith(".json"));
  const items = await Promise.all(files.map(async (file) => ({ ...JSON.parse(await readFile(resolve(source, file), "utf8")), kind })));
  return items.sort((a, b) => String(b.date).localeCompare(String(a.date)));
}

const projects = await loadCollection("projects", "project");
const sketches = await loadCollection("sketches", "sketch");
const output = resolve(root, "src/projects.generated.js");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `// Generated by npm run sync. Edit content/projects/*.json or content/sketches/*.json instead.\nexport const projects = ${JSON.stringify(projects, null, 2)};\nexport const sketches = ${JSON.stringify(sketches, null, 2)};\n`);
console.log(`Synced ${projects.length} projects and ${sketches.length} sketches.`);

const noteItems = await loadCollection("notes", "note");
const noteSlugs = new Set();
for (const note of noteItems) {
  const errors = validateNote(note, { draft: note.status === "draft" });
  if (noteSlugs.has(note.slug)) errors.push("Identificador duplicado.");
  noteSlugs.add(note.slug);
  if (errors.length) throw new Error(`Field Note ${note.slug}: ${errors.join(" ")}`);
}
const publishedNotes = noteItems.filter(note => note.status === "published");
for(const note of publishedNotes){
  const target=resolve(root,'public/notes',note.slug);await mkdir(target,{recursive:true});
  for(const item of note.media||[])await readFile(resolve(target,'media',item.file));
  await writeFile(resolve(target,'index.html'),publicationHTML(note));
}
await writeFile(resolve(root, "src/notes.generated.js"), `// Generated by npm run sync. Only approved published notes enter the browser bundle.\nexport const notes = ${JSON.stringify(publishedNotes, null, 2)};\n`);
console.log(`Synced ${publishedNotes.length} published Field Notes. Drafts remain excluded.`);
