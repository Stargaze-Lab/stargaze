import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function loadCollection(folder, kind) {
  const source = resolve(root, "content", folder);
  const files = (await readdir(source)).filter((file) => file.endsWith(".json"));
  const items = await Promise.all(files.map(async (file) => ({ ...JSON.parse(await readFile(resolve(source, file), "utf8")), kind })));
  return items.sort((a, b) => String(b.date).localeCompare(String(a.date)));
}

const projects = await loadCollection("projects", "project");
const sketches = await loadCollection("sketches", "sketch");
const output = resolve(root, "src/projects.generated.js");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `// Generated by npm run sync. Edit content/projects/*.json or content/sketches/*.json instead.\nexport const projects = ${JSON.stringify(projects, null, 2)};\nexport const sketches = ${JSON.stringify(sketches, null, 2)};\n`);
console.log(`Synced ${projects.length} projects and ${sketches.length} sketches.`);
